export function formatArticleDate(value: string, language: 'bn' | 'en' = 'en') {
  return new Intl.DateTimeFormat(language === 'bn' ? 'bn-BD' : 'en-BD', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
  }).format(new Date(value))
}

export function formatHistoryDate(value: string) {
  const date = new Date(value)
  const today = new Date()
  const isToday = date.toDateString() === today.toDateString()
  return isToday
    ? `Today, ${date.toLocaleTimeString('en-BD', { hour: 'numeric', minute: '2-digit' })}`
    : date.toLocaleDateString('en-BD', { day: 'numeric', month: 'short', hour: 'numeric', minute: '2-digit' })
}
